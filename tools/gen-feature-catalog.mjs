#!/usr/bin/env node
// Generates src/features/platform/data/feature-tabs.generated.js — every screen (route) of the organisation and
// employee portals with the tabs (features) it renders, read straight from the code:
//   src/routes/manifest.js → the view each route loads → the feature components that view imports (2 levels)
//   → <TabsTrigger value>.
// Run after adding a screen or a tab:  node tools/gen-feature-catalog.mjs
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const SRC = path.join(ROOT, "src");
const MANIFEST = path.join(SRC, "routes/manifest.js");
const OUT = path.join(SRC, "features/platform/data/feature-tabs.generated.js");

const read = (f) => fs.readFileSync(f, "utf8");
const resolveImport = (spec, fromFile) => {
  let base;
  if (spec.startsWith("@/")) base = path.join(SRC, spec.slice(2));
  else if (spec.startsWith(".")) base = path.resolve(path.dirname(fromFile), spec);
  else return null;
  for (const ext of ["", ".jsx", ".js", "/index.jsx", "/index.js"]) {
    const f = base + ext;
    if (fs.existsSync(f) && fs.statSync(f).isFile()) return f;
  }
  return null;
};
const importsOf = (file) =>
  [...read(file).matchAll(/from\s+"([^"]+)"/g)]
    .map((m) => resolveImport(m[1], file))
    .filter((f) => f && f.includes(`${path.sep}features${path.sep}`) && /\.jsx$/.test(f));

const clean = (s) =>
  s
    .replace(/\{[^}]*\}/g, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/\s+/g, " ")
    .trim();

function tabsOf(file) {
  const src = read(file);
  const out = [];
  const re = /<TabsTrigger\b([^>]*)>([\s\S]*?)<\/TabsTrigger>/g;
  let m;
  while ((m = re.exec(src))) {
    const v = /value=(?:"([^"]+)"|\{"([^"]+)"\})/.exec(m[1]);
    if (!v) continue;
    const value = v[1] ?? v[2];
    const label = clean(m[2]) || value;
    out.push({ value, label });
  }
  // Tab bars built from arrays: [{ value: "x", label: "Y" }] / { key: "x", label: "Y" } next to TabsTrigger value={t.value}
  if (/<TabsTrigger[^>]*value=\{\s*\w+\.(value|key|id)\s*\}/.test(src)) {
    const arr = /(value|key|id):\s*"([a-z0-9-_]+)",\s*(?:label|title|name):\s*"([^"]+)"/g;
    let a;
    while ((a = arr.exec(src))) out.push({ value: a[2], label: a[3] });
  }
  return out;
}

// Route → view module, straight from the manifest.
const routes = [...read(MANIFEST).matchAll(/path:\s*"([^"]+)"[\s\S]*?import\("([^"]+)"\)/g)].map(
  (m) => ({ route: m[1], view: m[2] }),
);

const screens = {};
for (const { route, view } of routes) {
  if (!/^\/(org|emp|helpdesk)(\/|$)/.test(route)) continue;
  if (route.includes(":")) continue;
  const entry = resolveImport(view, MANIFEST);
  if (!entry) continue;
  const seen = new Set();
  const tabs = [];
  const visit = (file, depth) => {
    if (!file || seen.has(file) || depth > 2) return;
    seen.add(file);
    for (const t of tabsOf(file)) if (!tabs.some((x) => x.value === t.value)) tabs.push(t);
    for (const f of importsOf(file)) visit(f, depth + 1);
  };
  visit(entry, 0);
  screens[route] = tabs;
}

const sorted = Object.fromEntries(Object.entries(screens).sort(([a], [b]) => a.localeCompare(b)));
const body = `// GENERATED by tools/gen-feature-catalog.mjs — do not edit by hand.
// Screen route → tabs (features) rendered on that screen, read from the code.
export const SCREEN_TABS = ${JSON.stringify(sorted, null, 2)};
`;
fs.writeFileSync(OUT, body);
console.log(
  `feature-tabs: ${Object.keys(sorted).length} screens, ${Object.values(sorted).reduce((n, t) => n + t.length, 0)} tabs → ${path.relative(ROOT, OUT)}`,
);
