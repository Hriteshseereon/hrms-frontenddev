export const addTemplate = (t) =>
  templateStore.set((p) => [
    { ...t, id: nextId("TPL", p.length), updated: new Date().toISOString().slice(0, 10) },
    ...p,
  ]);

export const updateTemplate = (id, patch) =>
  templateStore.set((p) =>
    p.map((t) =>
      t.id === id ? { ...t, ...patch, updated: new Date().toISOString().slice(0, 10) } : t,
    ),
  );

export const templatesOfKind = (rows, kind) =>
  rows.filter((t) => t.kind === kind && t.status === "Active");
